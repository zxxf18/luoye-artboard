 const pointer=(type,px=x,py=y)=>paper.dispatchEvent(new PointerEvent(type,{bubbles:true,pointerId:87,pointerType:'mouse',button:0,buttons:['pointerup','pointercancel'].includes(type)?0:1,clientX:px,clientY:py}));
 const saved=await snapshot();pointer('pointermove');await pause(100);check((await snapshot()).png===saved.png,'鼠标悬停预览不写入作品');
 const capture=paper.setPointerCapture;paper.setPointerCapture=()=>{};
 pointer('pointerdown');pointer('pointermove',x+80,y+20);pointer('pointerup',x+80,y+20);await idle();
 check((await snapshot()).png!==saved.png,'点击并拖动会留下仙女袋笔迹');
 const sizeBefore=$('size').value;$('asset-grid').children[1].click();await idle();check($('size').value===sizeBefore,'更换素材保留调整后的大小');
 [...document.querySelectorAll('.subtool-card')].find(b=>b.textContent.includes('会动图案')).click();$('asset-grid').children[0].click();await idle();
 const dynamicBefore=(await snapshot()).project.layers.length;pointer('pointerdown');await pause(750);pointer('pointerup');await idle();
 project=(await snapshot()).project;const dynamic=project.layers.at(-1);
 check(project.layers.length===dynamicBefore+1&&dynamic.sprites?.length>=4,'鼠标不松开持续盖章，整笔归为一个动画图层');
 check(dynamic.sprites.every(s=>s.size===96),'动态盖章使用调好的大小');
 pointer('pointermove');pointer('pointerleave');paper.setPointerCapture=capture;
 await pause(200);const painted=paper.getContext('2d').getImageData(0,0,paper.width,paper.height).data;check(painted.some((v,i)=>i%4!==3&&v<200),'屏幕画板实际显示笔迹和背景');
 $('layer-menu').click();await pause(100);
 check(!$('layer-dialog').querySelector('details').open,'高级图层操作默认收起');
